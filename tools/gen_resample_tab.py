#!/usr/bin/env python3
"""Generates src/snes/dsp_resample_tab.h: 16-tap Kaiser-windowed-sinc polyphase table
for the fixed 534 -> 735 frame resample done by dsp_getSamplesHQ (32040 Hz -> 44100 Hz).
Run:  python3 tools/gen_resample_tab.py > src/snes/dsp_resample_tab.h"""
import numpy as np
IN, OUT, TAPS = 534, 735, 16
FC, BETA, HALF = 0.47, 7.0, TAPS // 2   # cutoff in cycles/input-sample (Nyquist = 0.5)
tab = np.zeros((OUT, TAPS), dtype=np.int32)
for i in range(OUT):
    t = ((i * IN) % OUT) / OUT                 # exact fractional input position
    d = np.arange(TAPS) - 7 - t                # tap m is work frame k+m; P = k + 7 + t
    arg = np.clip(1 - (d / HALF) ** 2, 0, 1)
    w = np.sinc(2 * FC * d) * np.i0(BETA * np.sqrt(arg)) / np.i0(BETA)
    w /= w.sum()
    q = np.round(w * 32768).astype(np.int32)
    q[np.argmax(np.abs(q))] += 32768 - q.sum()  # exact unity DC gain
    tab[i] = q
assert (tab.sum(axis=1) == 32768).all()
assert np.abs(tab).sum(axis=1).max() * 32768 < 2**31, "int32 accumulator could overflow"
print("// Generated by tools/gen_resample_tab.py -- do not edit.")
print("// [output frame][tap], Q15, each row sums to 32768.")
print("static const int16_t kDspResampleTab[%d][%d] = {" % (OUT, TAPS))
for r in tab:
    print("  {" + ",".join(str(int(v)) for v in r) + "},")
print("};")
